import { test } from "node:test";
import assert from "node:assert/strict";
import { copyFileSync, cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import * as path from "node:path";
import { listSources, generateAll, dwhConvert, dwhCheck } from "../../src/dwh/sources.ts";
import { ROOT, realSources } from "./helpers.ts";

const FIXTURE = path.join(ROOT, "test", "dwh", "fixtures", "catalogue.min.json");
/** A catalogue path that does not exist: the repo as it is before dwh:catalogue has run. */
const NO_CAT = { cataloguePath: path.join(ROOT, "no-such-catalogue.json") };
const manifestOf = (files: Map<string, string>) => JSON.parse(files.get("queries/dwh/_manifest.json")!);
const entry = (m: any, src: string) => m.sources.find((s: any) => s.source === src);

/** A throwaway repo with the schema, the CSV, the mapping and a few sources. */
function tempRepo(sources: string[]): string {
  const dir = mkdtempSync(path.join(tmpdir(), "dwh-cli-"));
  cpSync(path.join(ROOT, "schema"), path.join(dir, "schema"), { recursive: true });
  copyFileSync(path.join(ROOT, "Database-Description-AMOS-csv.csv"), path.join(dir, "Database-Description-AMOS-csv.csv"));
  mkdirSync(path.join(dir, "dwh"));
  copyFileSync(path.join(ROOT, "dwh", "mapping.yaml"), path.join(dir, "dwh", "mapping.yaml"));
  for (const s of sources) {
    mkdirSync(path.dirname(path.join(dir, s)), { recursive: true });
    copyFileSync(path.join(ROOT, s), path.join(dir, s));
  }
  return dir;
}

test("listSources lists the root queries and queries/wp_seqs, sorted, with forward slashes", () => {
  assert.deepEqual(listSources(ROOT), realSources());
});

test("generateAll is stable across runs", () => {
  const a = generateAll(ROOT);
  const b = generateAll(ROOT);
  assert.deepEqual([...a.keys()], [...b.keys()]);
  for (const [k, v] of a) assert.equal(v, b.get(k), k);
  assert.ok(a.has("queries/dwh/extract_wp_seqs_steps.sql"));
  assert.ok(a.has("queries/dwh/wp_seqs/NTHN_steps.sql"));
});

test("manifest lists the two probe files as refused with E_LINT", () => {
  const m = manifestOf(generateAll(ROOT, NO_CAT));
  for (const p of ["probe_closed_dates.sql", "probe_workstep_duplicates.sql"]) {
    assert.equal(entry(m, p).status, "refused", p);
    assert.equal(entry(m, p).code, "E_LINT", p);
    assert.ok(entry(m, p).plain.length > 0);
  }
  assert.equal(m.sources.length, 27);
  assert.equal(entry(m, "extract_work_order.sql").code, "E_DUPLICATE_OUTPUT");
});

test("manifest marks extract_wp_seqs_steps as converted but not available, missing WP_STATUS and WP_DEPARTMENT_LINK", () => {
  const m = manifestOf(generateAll(ROOT, { cataloguePath: FIXTURE }));
  const e = entry(m, "extract_wp_seqs_steps.sql");
  assert.equal(e.status, "converted");
  assert.equal(e.output, "queries/dwh/extract_wp_seqs_steps.sql");
  assert.equal(e.available, false);
  assert.deepEqual(e.missing, ["WP_DEPARTMENT_LINK", "WP_STATUS"]);
  assert.equal(entry(m, "extract_all_parts.sql").available, true);
  // Without a snapshot, the missing tables recorded in dwh/mapping.yaml are used; columns stay unchecked.
  const noCat = manifestOf(generateAll(ROOT, NO_CAT));
  assert.equal(entry(noCat, "extract_wp_seqs_steps.sql").available, false);
  assert.deepEqual(entry(noCat, "extract_wp_seqs_steps.sql").missing, ["WP_DEPARTMENT_LINK", "WP_STATUS"]);
  assert.equal(entry(noCat, "extract_all_parts.sql").available, "unknown");
});

test("header has source hash, availability and warning codes, and no date", () => {
  const files = generateAll(ROOT, { cataloguePath: FIXTURE });
  const text = files.get("queries/dwh/extract_wp_seqs_steps.sql")!;
  const header = text.split("\n").filter((l) => l.startsWith("--"));
  assert.match(header[0]!, /^-- GENERATED by `npm run dwh:convert`\. DO NOT EDIT/);
  assert.ok(header.some((l) => /^-- Source: extract_wp_seqs_steps\.sql {2}sha256:[0-9a-f]{12}$/.test(l)));
  assert.ok(header.some((l) => /^-- Converter: 2 {3}Catalogue snapshot: sha256:[0-9a-f]{12}$/.test(l)));
  assert.ok(header.some((l) => l === "-- Available in the DWH: NO (missing: WP_DEPARTMENT_LINK, WP_STATUS)"));
  assert.ok(header.some((l) => l.startsWith("-- Warning W_UTC_TODAY:")));
  assert.ok(header.some((l) => l.startsWith("-- Warning W_STRING_ORDER:")));
  for (const l of header) assert.ok(!/\d{4}-\d{2}-\d{2}|\d{2}:\d{2}/.test(l), `date in header: ${l}`);
  assert.ok(!text.includes("\r"));
  assert.ok(text.endsWith("\n"));
  const noCat = generateAll(ROOT, NO_CAT);
  const steps = noCat.get("queries/dwh/extract_wp_seqs_steps.sql")!;
  assert.ok(steps.includes("-- Available in the DWH: NO (missing tables listed in dwh/mapping.yaml: WP_DEPARTMENT_LINK, WP_STATUS; columns not checked yet)"));
  assert.ok(steps.includes("-- Converter: 2   Catalogue snapshot: none"));
  assert.ok(noCat.get("queries/dwh/extract_all_parts.sql")!.includes("-- Available in the DWH: unknown (no missing tables known; columns are checked once a catalogue snapshot exists)"));
});

test("dwhConvert writes and removes files; dwhCheck reports hand edits, missing files and deleted sources", () => {
  const dir = tempRepo(["extract_all_parts.sql", "extract_han_workpacks_today.sql", "probe_closed_dates.sql"]);
  try {
    const r = dwhConvert(dir);
    assert.deepEqual(r.refused, ["probe_closed_dates.sql"]);
    assert.deepEqual(r.written, ["queries/dwh/_manifest.json", "queries/dwh/extract_all_parts.sql", "queries/dwh/extract_han_workpacks_today.sql"]);
    assert.deepEqual(dwhCheck(dir), []);

    // A checkout with CRLF line ends is not a difference.
    const gen = path.join(dir, "queries", "dwh", "extract_all_parts.sql");
    writeFileSync(gen, readFileSync(gen, "utf8").replace(/\n/g, "\r\n"));
    assert.deepEqual(dwhCheck(dir), []);

    // dwhCheck reports a hand-edited generated file.
    writeFileSync(gen, readFileSync(gen, "utf8").replace("PART.PARTNO", "PART.PARTNO_EDITED"));
    const edited = dwhCheck(dir);
    assert.equal(edited.length, 1);
    assert.match(edited[0]!, /queries\/dwh\/extract_all_parts\.sql/);

    // dwhCheck reports a generated file whose source was deleted.
    dwhConvert(dir);
    rmSync(path.join(dir, "extract_han_workpacks_today.sql"));
    const orphan = dwhCheck(dir);
    assert.ok(orphan.some((p) => /queries\/dwh\/extract_han_workpacks_today\.sql/.test(p)), orphan.join("\n"));
    assert.deepEqual(dwhConvert(dir).removed, ["queries/dwh/extract_han_workpacks_today.sql"]);
    assert.ok(!existsSync(path.join(dir, "queries", "dwh", "extract_han_workpacks_today.sql")));
    assert.deepEqual(dwhCheck(dir), []);

    // A missing generated file is reported too.
    rmSync(gen);
    assert.ok(dwhCheck(dir).some((p) => /extract_all_parts\.sql/.test(p)));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("with a catalogue, generateAll also writes docs/generated/dwh-schema-diff.md; without one it does not", () => {
  const withCat = generateAll(ROOT, { cataloguePath: FIXTURE });
  const md = withCat.get("docs/generated/dwh-schema-diff.md");
  assert.ok(md, "diff file generated");
  assert.match(md!, /\| error \| missing_table \| WP_STATUS \|/);
  assert.match(md!, /truncation_risk \| WO_TEXT_DESCRIPTION \| TEXT_HTML/);
  const without = generateAll(ROOT, { cataloguePath: path.join(ROOT, "no-such-catalogue.json") });
  assert.equal(without.has("docs/generated/dwh-schema-diff.md"), false);
});

test("dwhCheck reports a stale schema diff file", () => {
  const dir = tempRepo(["extract_all_parts.sql"]);
  try {
    copyFileSync(FIXTURE, path.join(dir, "dwh", "catalogue.json"));
    dwhConvert(dir);
    assert.deepEqual(dwhCheck(dir), []);
    const p = path.join(dir, "docs", "generated", "dwh-schema-diff.md");
    writeFileSync(p, readFileSync(p, "utf8").replace("Errors:", "Errorz:"));
    assert.ok(dwhCheck(dir).some((x) => x.includes("dwh-schema-diff.md")));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
