// Task 1.7: convert every source query into queries/dwh/ (Oracle SQL, pretty rendering) plus
// queries/dwh/_manifest.json, and check the committed files are current. No database access.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import * as path from "node:path";
import { loadModel } from "../schema/load.ts";
import { loadCsvIndex } from "../schema/csv.ts";
import { loadMapping } from "./mapping.ts";
import { loadCatalogue } from "./catalogue.ts";
import { ConvertError } from "./convert/errors.ts";
import { CONVERTER_VERSION, convertQuery, type ConvertResult } from "./convert/index.ts";

const OUT_DIR = "queries/dwh";
const MANIFEST = `${OUT_DIR}/_manifest.json`;

const lf = (s: string) => s.replace(/\r\n?/g, "\n");
const sha256 = (s: string) => createHash("sha256").update(s, "utf8").digest("hex");

/** Root *.sql and queries/wp_seqs/*.sql, relative to root with forward slashes, sorted. */
export function listSources(root: string): string[] {
  const inDir = (dir: string) => {
    const abs = path.join(root, dir);
    if (!existsSync(abs)) return [];
    return readdirSync(abs, { withFileTypes: true })
      .filter((d) => d.isFile() && d.name.endsWith(".sql") && d.name !== "AMOS-WO.sql")
      .map((d) => d.name)
      .sort()
      .map((f) => (dir === "." ? f : `${dir}/${f}`));
  };
  return [...inDir("."), ...inDir("queries/wp_seqs")];
}

/** Where a source's Oracle version lives: queries/wp_seqs/X.sql -> queries/dwh/wp_seqs/X.sql. */
export function outputPathOf(source: string): string {
  return `${OUT_DIR}/${source.replace(/^queries\//, "")}`;
}

function availabilityLine(r: ConvertResult): string {
  if (r.available === "unknown") return "-- Available in the DWH: unknown (no catalogue snapshot yet)";
  return r.available ? "-- Available in the DWH: yes" : `-- Available in the DWH: NO (missing: ${r.missing.join(", ")})`;
}

function fileText(source: string, sourceSha: string, catalogueSha: string | undefined, mappingLinked: string, schema: string, r: ConvertResult): string {
  const header = [
    "-- GENERATED by `npm run dwh:convert`. DO NOT EDIT: edit the source and re-run.",
    `-- Oracle SQL for the DWH (${schema}), sent through the ${mappingLinked} linked server by the DWH runner.`,
    `-- Source: ${source}  sha256:${sourceSha.slice(0, 12)}`,
    `-- Converter: ${CONVERTER_VERSION}   Catalogue snapshot: ${catalogueSha ? `sha256:${catalogueSha.slice(0, 12)}` : "none"}`,
    availabilityLine(r),
    ...r.placeholders.map((p) => `-- Placeholder: <${p.name}> (filled in when the query runs)`),
    ...r.warnings.map((w) => `-- Warning ${w.code}: ${w.plain}`),
  ];
  return `${header.join("\n")}\n\n${r.pretty}\n`;
}

/** Every generated file (path relative to root -> content, LF line ends), manifest included. */
export function generateAll(root: string, opts: { cataloguePath?: string } = {}): Map<string, string> {
  const model = loadModel(path.join(root, "schema"));
  const csv = loadCsvIndex(path.join(root, "Database-Description-AMOS-csv.csv"));
  const mappingText = lf(readFileSync(path.join(root, "dwh", "mapping.yaml"), "utf8"));
  const mapping = loadMapping(path.join(root, "dwh", "mapping.yaml"));
  const cataloguePath = opts.cataloguePath ?? path.join(root, "dwh", "catalogue.json");
  const catalogue = loadCatalogue(cataloguePath);
  const catalogueSha = catalogue ? sha256(lf(readFileSync(cataloguePath, "utf8"))) : undefined;

  const files = new Map<string, string>();
  const entries: unknown[] = [];
  for (const source of listSources(root)) {
    const text = lf(readFileSync(path.join(root, source), "utf8"));
    const sourceSha = sha256(text);
    try {
      const r = convertQuery(text, source, { model, csv, mapping, ...(catalogue ? { catalogue } : {}) });
      const output = outputPathOf(source);
      files.set(output, fileText(source, sourceSha, catalogueSha, mapping.linkedServer, mapping.oracleSchema, r));
      entries.push({
        source,
        sourceSha256: sourceSha,
        status: "converted",
        output,
        available: r.available,
        missing: r.missing,
        warnings: r.warnings,
        placeholders: r.placeholders,
        outputs: r.outputs,
        orderKeys: r.orderKeys,
        usedColumns: r.usedColumns,
        execLength: r.exec.length,
      });
    } catch (e) {
      if (!(e instanceof ConvertError)) throw e;
      entries.push({
        source,
        sourceSha256: sourceSha,
        status: "refused",
        code: e.code,
        plain: e.plain,
        ...(e.detail ? { detail: e.detail } : {}),
        ...(e.loc ? { line: e.loc.line, column: e.loc.column } : {}),
      });
    }
  }
  const manifest = {
    generated: "GENERATED by `npm run dwh:convert`. DO NOT EDIT.",
    converterVersion: CONVERTER_VERSION,
    mappingSha256: sha256(mappingText),
    catalogueSha256: catalogueSha ?? null,
    execMode: mapping.execMode,
    sources: entries,
  };
  files.set(MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`);
  return new Map([...files.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

/** Generated files currently on disk under queries/dwh/ (relative paths). */
function existingGenerated(root: string): string[] {
  const out: string[] = [];
  const walk = (rel: string) => {
    const abs = path.join(root, rel);
    if (!existsSync(abs)) return;
    for (const d of readdirSync(abs, { withFileTypes: true })) {
      const child = `${rel}/${d.name}`;
      if (d.isDirectory()) walk(child);
      else if (d.name.endsWith(".sql") || child === MANIFEST) out.push(child);
    }
  };
  walk(OUT_DIR);
  return out.sort();
}

export function dwhConvert(root: string): { written: string[]; removed: string[]; refused: string[] } {
  const files = generateAll(root);
  const written: string[] = [];
  for (const [rel, content] of files) {
    const abs = path.join(root, rel);
    if (existsSync(abs) && lf(readFileSync(abs, "utf8")) === content) continue;
    mkdirSync(path.dirname(abs), { recursive: true });
    writeFileSync(abs, content, "utf8");
    written.push(rel);
  }
  const removed = existingGenerated(root).filter((rel) => !files.has(rel));
  for (const rel of removed) rmSync(path.join(root, rel));
  const manifest = JSON.parse(files.get(MANIFEST)!) as { sources: { source: string; status: string }[] };
  const refused = manifest.sources.filter((s) => s.status === "refused").map((s) => s.source);
  return { written, removed, refused };
}

/** Problems with the committed queries/dwh/ files (empty = up to date). */
export function dwhCheck(root: string): string[] {
  const files = generateAll(root);
  const problems: string[] = [];
  for (const [rel, content] of files) {
    const abs = path.join(root, rel);
    if (!existsSync(abs)) problems.push(`${rel} is missing. Run npm run dwh:convert.`);
    else if (lf(readFileSync(abs, "utf8")) !== content) problems.push(`${rel} is out of date or was edited by hand. Run npm run dwh:convert.`);
  }
  for (const rel of existingGenerated(root)) {
    if (!files.has(rel)) problems.push(`${rel} has no source any more (deleted, renamed or now refused). Run npm run dwh:convert to remove it.`);
  }
  return problems;
}
