import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import * as path from "node:path";

export type Pair = { station: string; department: string };

const STATION = "wp_header.station = 'HAN'";
const DEPARTMENT = "wp_department_link.department = 'NTHN'";

/** Render the root template (HAN / NTHN) for one station-department pair. */
export function renderPair(template: string, pair: Pair, kind: "steps" | "parts"): string {
  if (!template.includes(STATION) || !template.includes(DEPARTMENT))
    throw new Error(`Template for ${kind} lost its HAN/NTHN filter lines`);
  const banner = `-- GENERATED by \`npm run scaffold\` from extract_wp_seqs_${kind}.sql for ${pair.station}-${pair.department}. Edit the root template, not this file.\n`;
  return banner + template
    .replace(STATION, `wp_header.station = '${pair.station}'`)
    .replace(DEPARTMENT, `wp_department_link.department = '${pair.department}'`);
}

export function scaffoldWpSeqs(root: string): string[] {
  const dir = path.join(root, "queries", "wp_seqs");
  const pairs: Pair[] = JSON.parse(readFileSync(path.join(dir, "pairs.json"), "utf8"));
  mkdirSync(dir, { recursive: true });
  const written: string[] = [];
  for (const kind of ["steps", "parts"] as const) {
    const template = readFileSync(path.join(root, `extract_wp_seqs_${kind}.sql`), "utf8").split("\r").join("");
    for (const pair of pairs) {
      const file = path.join(dir, `${pair.station}-${pair.department}_${kind}.sql`);
      writeFileSync(file, renderPair(template, pair, kind), "utf8");
      written.push(file);
    }
  }
  return written;
}
